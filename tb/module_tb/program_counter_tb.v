`timescale 1ns/1ps

module program_counter_tb;

    //==================================================
    // Testbench Signals
    //==================================================

    reg         clk;
    reg         rst;
    reg  [31:0] next_pc;

    wire [31:0] pc;

    //==================================================
    // DUT
    //==================================================

    program_counter dut (
        .clk(clk),
        .rst(rst),
        .next_pc(next_pc),
        .pc(pc)
    );

    //==================================================
    // Clock Generation
    // 10 ns period
    //==================================================

    initial begin
        clk = 0;
        forever #5 clk = ~clk;
    end

    //==================================================
    // Waveform
    //==================================================

    initial begin
        $dumpfile("program_counter_tb.vcd");
        $dumpvars(0, program_counter_tb);
    end

    //==================================================
    // Monitor
    //==================================================

    initial begin
        $monitor("Time=%0t rst=%b next_pc=%h pc=%h",
                 $time, rst, next_pc, pc);
    end

    //==================================================
    // Stimulus
    //==================================================

    initial begin

        //----------------------------------------------
        // Initialize
        //----------------------------------------------

        rst     = 1;
        next_pc = 32'h00000000;

        //----------------------------------------------
        // Test 1 : Reset
        //----------------------------------------------

        #12;

        if (pc == 32'h00000000)
            $display("PASS : Reset");
        else
            $display("FAIL : Reset");

        //----------------------------------------------
        // Release Reset
        //----------------------------------------------

        rst = 0;

        //----------------------------------------------
        // Test 2 : PC = 4
        //----------------------------------------------

        next_pc = 32'h00000004;
        @(posedge clk);

        #1;

        if (pc == 32'h00000004)
            $display("PASS : PC = 4");
        else
            $display("FAIL : PC = 4");

        //----------------------------------------------
        // Test 3 : PC = 8
        //----------------------------------------------

        next_pc = 32'h00000008;
        @(posedge clk);

        #1;

        if (pc == 32'h00000008)
            $display("PASS : PC = 8");
        else
            $display("FAIL : PC = 8");

        //----------------------------------------------
        // Test 4 : Large Address
        //----------------------------------------------

        next_pc = 32'h00000100;
        @(posedge clk);

        #1;

        if (pc == 32'h00000100)
            $display("PASS : Large Address");
        else
            $display("FAIL : Large Address");

        //----------------------------------------------
        // Finish
        //----------------------------------------------

        #10;
        $display("--------------------------------");
        $display("Program Counter Test Completed");
        $display("--------------------------------");
        $finish;

    end

endmodule